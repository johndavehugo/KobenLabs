<?php

namespace App\Models;

use App\Enums\GroupMessageType;
use Database\Factories\GroupChatMessageFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\Scope;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Database\Eloquent\Relations\BelongsToMany;
use Illuminate\Database\Eloquent\Relations\HasMany;

/**
 * A single message inside a chat group.
 *
 * `sender_id` is nullable: join and leave notifications are generated by the
 * system and have no author.
 */
#[Fillable([
    'group_chat_id',
    'sender_id',
    'body',
    'type',
    'file_path',
    'file_name',
    'file_size',
    'reply_to_id',
])]
class GroupChatMessage extends Model
{
    /** @use HasFactory<GroupChatMessageFactory> */
    use HasFactory;

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'type' => GroupMessageType::class,
            'file_size' => 'integer',
        ];
    }

    public function groupChat(): BelongsTo
    {
        return $this->belongsTo(GroupChat::class);
    }

    public function sender(): BelongsTo
    {
        return $this->belongsTo(User::class, 'sender_id');
    }

    public function replyTo(): BelongsTo
    {
        return $this->belongsTo(self::class, 'reply_to_id');
    }

    public function replies(): HasMany
    {
        return $this->hasMany(self::class, 'reply_to_id');
    }

    /**
     * Read receipts. The pivot stores `read_at` rather than Laravel's default
     * timestamps, and its key is `message_id` rather than the conventional
     * `<model>_id`, so both are declared explicitly.
     */
    public function readBy(): BelongsToMany
    {
        return $this->belongsToMany(
            User::class,
            'group_message_reads',
            'message_id',
            'user_id',
        )->withPivot('read_at');
    }

    // -----------------------------------------------------------------
    // Scopes
    // -----------------------------------------------------------------

    #[Scope]
    public function ofType(Builder $query, GroupMessageType $type): void
    {
        $query->where('type', $type);
    }

    #[Scope]
    public function fromUsers(Builder $query): void
    {
        $query->whereNotNull('sender_id');
    }

    // -----------------------------------------------------------------
    // Behaviour
    // -----------------------------------------------------------------

    public function isSystem(): bool
    {
        return $this->type === GroupMessageType::System;
    }

    public function hasAttachment(): bool
    {
        return in_array($this->type, [GroupMessageType::File, GroupMessageType::Image], true)
            && $this->file_path !== null;
    }

    public function markReadBy(User $user): void
    {
        $this->readBy()->syncWithoutDetaching([
            $user->id => ['read_at' => now()],
        ]);
    }
}
